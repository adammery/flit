fn main() {
    // why: sqlx::migrate!() embeds the migrations at compile time, but a
    // proc macro can't ask the compiler to watch a directory — a new .sql
    // file alone rebuilt nothing, and the app kept the old migration set.
    // sqlx's docs prescribe exactly this line for stable Rust.
    println!("cargo:rerun-if-changed=migrations");
    // why an app manifest: without one, Tauri lets every window call every
    // registered command, and the capability files only govern plugins.
    // Declaring the commands makes each one a permission (allow-<name>) that
    // a window must be granted in capabilities/ — see main.json,
    // settings.json and compose.json for who gets what.
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(APP_COMMANDS)),
    )
    .expect("tauri-build failed");
}

